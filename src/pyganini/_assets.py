@dataclass(slots=True)
class _AssetLease:
    filesystem: AnchoredFilesystem | None
    build_filesystem: AnchoredFilesystem | None

    def require(self) -> AnchoredFilesystem:
        if self.filesystem is None:
            raise AssetError(
                "PYGANINI022",
                "asset-write",
                _display(_ASSETS),
                "prepared asset operation is already closed",
            )
        return self.filesystem

    def close(self) -> None:
        failure: OSError | None = None
        build_filesystem = self.build_filesystem
        if build_filesystem is not None:
            self.build_filesystem = None
            try:
                build_filesystem.close()
            except OSError as error:
                failure = error
        filesystem = self.filesystem
        if filesystem is not None:
            self.filesystem = None
            try:
                filesystem.close()
            except OSError as error:
                if failure is None:
                    failure = error
        if failure is not None:
            raise failure

    def verify_build(self) -> None:
        filesystem = self.build_filesystem
        if filesystem is None:
            return
        _verify_anchor(filesystem, _BUILD, "asset build directory")


