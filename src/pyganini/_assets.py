class AssetError(RuntimeError):
    """A localized asset validation, comparison, or write failure."""

    def __init__(
        self,
        code: str,
        phase: str,
        path: str,
        message: str,
        *,
        details: Sequence[str] = (),
    ) -> None:
        super().__init__(message)
        self.code = code
        self.phase = phase
        self.path = path
        self.message = message
        self.details = tuple(details)


