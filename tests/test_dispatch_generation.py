def test_rendered_router_mounts_under_starlette_and_fastapi(
    tmp_path: Path, make_app: Callable[..., Path]
) -> None:
    application = make_app(tmp_path / "application")
    _write_render_tree(application)
    assert main(["generate", "--app-root", str(application)]) == 0

    with _generated_module(application) as generated:
        starlette_host = Starlette(routes=[Mount("/html", app=generated.router)])
        with TestClient(starlette_host) as client:
            assert client.get("/html/users").status_code == 200

        fastapi_host = FastAPI()

        @fastapi_host.get("/api/health")
        async def health() -> dict[str, str]:
            return {"status": "ok"}

        assert callable(health)
        fastapi_host.mount("/html", generated.create_router())
        with TestClient(fastapi_host) as client:
            assert client.get("/html/users/table").text == "<p>&lt;one&gt;</p>"
            assert client.get("/api/health").json() == {"status": "ok"}
            assert "/api/health" in client.get("/openapi.json").json()["paths"]
            assert "/html/users" not in client.get("/openapi.json").json()["paths"]


def test_template_content_does_not_change_generated_bytes_but_name_does(
    tmp_path: Path, make_app: Callable[..., Path]
) -> None:
    application = make_app(tmp_path / "application")
    _write_render_tree(application)
    paths = select_project_paths(explicit=application, start=application)
    first = dispatch_plan(build_route_graph(paths))[0].content

    page_template = application / "app" / "routes" / "users" / "page.jinja"
    page_template.write_text("changed product text\n", encoding="ascii")
    assert dispatch_plan(build_route_graph(paths))[0].content == first

    route_file = page_template.with_name("route.py")
    route_file.write_text(
        route_file.read_text(encoding="ascii").replace(
            "template='page.jinja'", "template='other.jinja'", 1
        ),
        encoding="ascii",
    )
    page_template.with_name("other.jinja").write_text(
        "changed product text\n", encoding="ascii"
    )
    assert dispatch_plan(build_route_graph(paths))[0].content != first
