def test_generated_error_render_values_use_root_and_matched_layouts(
    tmp_path: Path, make_app: Callable[..., Path]
) -> None:
    application = make_app(tmp_path / "application")
    routes = application / "app" / "routes"
    (routes / "layout.py").write_text("", encoding="ascii")
    (routes / "layout.jinja").write_text("<root>{{ child }}</root>", encoding="ascii")
    (routes / "error_page.jinja").write_text("<h1>{{ message }}</h1>", encoding="ascii")
    (routes / "error_fragment.jinja").write_text(
        "<aside>{{ message }}</aside>", encoding="ascii"
    )
    (routes / "route.py").write_text(
        "from pyganini import route\n"
        "Route = route(\n"
        "    error_page_template='error_page.jinja',\n"
        "    error_fragment_template='error_fragment.jinja',\n"
        ")\n",
        encoding="ascii",
    )
    users = routes / "users"
    users.mkdir()
    (users / "__init__.py").write_text("", encoding="ascii")
    (users / "layout.py").write_text("", encoding="ascii")
    (users / "layout.jinja").write_text(
        "<nested>{{ child }}</nested>", encoding="ascii"
    )
    (users / "page.jinja").write_text("unused", encoding="ascii")
    (users / "route.py").write_text(
        "from starlette.exceptions import HTTPException\n"
        "from pyganini import route\n"
        "def page(request): raise HTTPException(status_code=422)\n"
        "Route = route(page=page, template='page.jinja')\n",
        encoding="ascii",
    )
    assert main(["generate", "--app-root", str(application)]) == 0

    def present(request: Request, error: Exception) -> Page | FragmentResponse:
        assert isinstance(error, HTTPException)
        message = f"status {error.status_code}"
        if request.headers.get("HX-Request") == "true":
            return FragmentResponse(
                context={"message": message}, status_code=error.status_code
            )
        return Page(
            context={"message": message},
            metadata=PageMetadata(title="Error"),
            layout={},
            status_code=error.status_code,
        )

    with _generated_module(application) as generated:
        router = generated.create_router(error_handler=present)
        with TestClient(router) as client:
            missing = client.get("/missing")
            wrong_method = client.post("/users")
            matched = client.get("/users")
            fragment = client.get("/users", headers={"HX-Request": "true"})
            head = client.head("/missing")

    assert missing.text == "<root><h1>status 404</h1></root>"
    assert wrong_method.text == "<root><h1>status 405</h1></root>"
    assert set(wrong_method.headers["allow"].split(", ")) == {"GET", "HEAD"}
    assert matched.text == ("<root><nested><h1>status 422</h1></nested></root>")
    assert fragment.text == "<aside>status 422</aside>"
    assert head.status_code == 404
    assert head.content == b""


