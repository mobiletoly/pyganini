def test_second_replacement_failure_cleans_remaining_stage_and_reports_partial(
    tmp_path: Path,
    make_app: Callable[..., Path],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    application = make_app(tmp_path / "application")
    paths = _paths(application)
    plan = (
        GeneratedArtifact(PurePosixPath("app/_pyganini/a.txt"), b"a\n"),
        GeneratedArtifact(PurePosixPath("app/_pyganini/b.txt"), b"b\n"),
    )
    generate(paths, plan)
    (paths.generated / "a.txt").write_bytes(b"old-a\n")
    (paths.generated / "b.txt").write_bytes(b"old-b\n")
    original = filesystem_module._PosixGeneratedFilesystem.replace
    replacements = 0

    def fail_second(self: Any, staged: Any) -> None:
        nonlocal replacements
        replacements += 1
        if replacements == 2:
            raise OSError("injected second replacement failure")
        original(self, staged)

    monkeypatch.setattr(
        filesystem_module._PosixGeneratedFilesystem, "replace", fail_second
    )
    with pytest.raises(GenerationError) as captured:
        generate(paths, plan)
    assert captured.value.code == "PYGANINI008"
    assert any(
        "replaced app/_pyganini/a.txt" in item for item in captured.value.details
    )
    assert not tuple(paths.generated.rglob("._pyganini-*"))
    assert check_generated_state(paths, plan) != ()
    monkeypatch.undo()
    generate(paths, plan)
    assert not check_generated_state(paths, plan)


def test_post_replacement_scan_failure_is_partial_generation(
    tmp_path: Path,
    make_app: Callable[..., Path],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    application = make_app(tmp_path / "application")
    paths = _paths(application)
    generate(paths, bootstrap_plan())
    (paths.generated / "__init__.py").write_bytes(b"stale\n")
    original = filesystem_module._PosixGeneratedFilesystem.entries
    calls = 0

    def fail_after_replace(self: Any) -> object:
        nonlocal calls
        calls += 1
        if calls == 2:
            raise RuntimeError("injected post-mutation scan failure")
        return original(self)

    monkeypatch.setattr(
        filesystem_module._PosixGeneratedFilesystem, "entries", fail_after_replace
    )
    with pytest.raises(GenerationError) as captured:
        generate(paths, bootstrap_plan())
    assert captured.value.code == "PYGANINI008"
    assert "replaced app/_pyganini/__init__.py" in captured.value.details[0]
