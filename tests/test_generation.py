MARKER = b"pyganini-generated-directory-v1\n"
BOOTSTRAP = (
    b"# Code generated by pyganini; DO NOT EDIT.\n"
    b'"""Generated Pyganini application package."""\n'
)


def _paths(application: Path) -> ProjectPaths:
    return select_project_paths(explicit=application, start=application)


def _snapshot(root: Path) -> tuple[tuple[str, str, bytes | None, int], ...]:
    records: list[tuple[str, str, bytes | None, int]] = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        if path.is_symlink():
            records.append(
                (relative, "link", os.readlink(path).encode(), path.lstat().st_mtime_ns)
            )
        elif path.is_dir():
            records.append((relative, "directory", None, path.stat().st_mtime_ns))
        else:
            records.append(
                (relative, "file", path.read_bytes(), path.stat().st_mtime_ns)
            )
    return tuple(records)


def test_first_generation_is_exact_and_idempotent(
    tmp_path: Path, make_app: Callable[..., Path]
) -> None:
    application = make_app(tmp_path / "application")
    paths = _paths(application)

    first = generate(paths, bootstrap_plan())
    assert [path.as_posix() for path in first.written] == [
        "app/_pyganini/.pyganini-root",
        "app/_pyganini/__init__.py",
    ]
    assert not first.unchanged
    assert not first.removed
    assert (paths.generated / ".pyganini-root").read_bytes() == MARKER
    assert (paths.generated / "__init__.py").read_bytes() == BOOTSTRAP

    bootstrap = paths.generated / "__init__.py"
    before = bootstrap.stat().st_mtime_ns
    time.sleep(0.002)
    second = generate(paths, bootstrap_plan())
    assert not second.written
    assert [path.as_posix() for path in second.unchanged] == [
        "app/_pyganini/.pyganini-root",
        "app/_pyganini/__init__.py",
    ]
    assert bootstrap.stat().st_mtime_ns == before
    assert not check_generated_state(paths, bootstrap_plan())


