def test_all_files_stage_before_any_replacement(
    tmp_path: Path,
    make_app: Callable[..., Path],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    application = make_app(tmp_path / "application")
    paths = _paths(application)
    plan = (
        GeneratedArtifact(PurePosixPath("app/_pyganini/a.txt"), b"a\n"),
        GeneratedArtifact(PurePosixPath("app/_pyganini/b.txt"), b"b\n"),
    )
    generate(paths, plan)
    (paths.generated / "a.txt").write_bytes(b"old-a\n")
    (paths.generated / "b.txt").write_bytes(b"old-b\n")
    events: list[str] = []
    original_stage = filesystem_module._PosixGeneratedFilesystem.stage
    original_replace = filesystem_module._PosixGeneratedFilesystem.replace

    def record_stage(self: Any, relative: PurePosixPath, content: bytes) -> object:
        events.append(f"stage:{relative}")
        return original_stage(self, relative, content)

    def record_replace(self: Any, staged: Any) -> None:
        events.append(f"replace:{staged.destination_name}")
        original_replace(self, staged)

    monkeypatch.setattr(
        filesystem_module._PosixGeneratedFilesystem, "stage", record_stage
    )
    monkeypatch.setattr(
        filesystem_module._PosixGeneratedFilesystem, "replace", record_replace
    )
    generate(paths, plan)
    assert events == ["stage:a.txt", "stage:b.txt", "replace:a.txt", "replace:b.txt"]


