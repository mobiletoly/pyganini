    application = make_app(tmp_path / "application")
    paths = _paths(application)
    generate(paths, bootstrap_plan())
    (paths.generated / "__init__.py").write_bytes(b"stale\n")
    original_unlink = cast(Callable[..., object], os.unlink)

    def fail_unlink(name: object, *args: object, **kwargs: object) -> object:
        if isinstance(name, str) and name.startswith("._pyganini-"):
            raise OSError("injected staging cleanup failure")
        return original_unlink(name, *args, **kwargs)

    def fail_fsync(_: int) -> None:
        raise OSError("injected fsync failure")

    monkeypatch.setattr(os, "unlink", fail_unlink)
    monkeypatch.setattr(os, "fsync", fail_fsync)
    with pytest.raises(GenerationError) as captured:
        generate(paths, bootstrap_plan())
    assert captured.value.code == "PYGANINI007"
    assert "injected fsync failure" in captured.value.message
    assert "injected staging cleanup failure" in captured.value.message
    assert tuple(paths.generated.rglob("._pyganini-*"))


